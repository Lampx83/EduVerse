//   { reagentId, displayName, targetAmount, unit ('g'|'mL'), tolerance, container ('beaker'|'cylinder'|'beaker-from-cylinder') }
//
// `container` semantics:
//   - 'beaker'                 → pour reagent directly into beaker (which sits on the balance for weight steps)
